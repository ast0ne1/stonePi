"""Generate ``static/css/tokens.css`` from ``tokens.json`` (the design system's export).

    python packages/stonepi_brand/build_tokens.py          # write tokens.css
    python packages/stonepi_brand/build_tokens.py --check  # exit 1 if it is stale

``tokens.json`` is copied verbatim from the StonePi design system
(https://claude.ai/artifact/GmoWFVDw7af2fpXFZMNCMP, ``project/tokens.json``).
Update that file, re-run this script, never hand-edit tokens.css.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "tokens.json"
TARGET = HERE / "static" / "css" / "tokens.css"
# The install site (Vercel, install-stonepi/) is standalone, so it gets its own copy.
EXTRA_TARGETS = (HERE.parents[1] / "install-stonepi" / "assets" / "tokens.css",)

# Names every app.css already uses, mapped to design-system roles so app layout
# rules pick up the new look without per-app palettes. New CSS should use the
# role names directly.
LEGACY_ALIASES = {
    "paper": "var(--canvas)",
    "wash": "var(--surface)",
    "card": "var(--surface-raised)",
    "ink": "var(--text)",
    "muted": "var(--text-muted)",
    "line": "var(--border)",
    "accent": "var(--primary)",
    "accent-ink": "var(--primary-ink)",
    "ok": "var(--success-text)",
    "warn": "var(--warning-text)",
    "error": "var(--danger-text)",
    "shadow": "none",
    "radius": "var(--radius-lg)",
    "chrome": "var(--font-sans)",
    "serif": "var(--font-display)",
    "mono": "var(--font-mono)",
    "theme-meta": "var(--surface)",
    "scroll-thumb": "var(--border-control)",
    "scroll-thumb-hover": "var(--text-faint)",
    "scroll-track": "transparent",
}

# Motion (README → Motion); not in tokens.json.
MOTION = {
    "duration-fast": "140ms",
    "duration-menu": "200ms",
    "ease-out": "cubic-bezier(0.2, 0, 0, 1)",
}


def _block(selector: str, lines: list[str], indent: str = "") -> str:
    body = "\n".join(f"{indent}  {line}" for line in lines)
    return f"{indent}{selector} {{\n{body}\n{indent}}}"


def _theme_lines(tokens: dict, theme: str) -> list[str]:
    lines = [f"color-scheme: {theme};"]
    for tok in tokens["color"]["tokens"]:
        lines.append(f"--{tok['name']}: {tok['value'][theme]};")
    for tok in tokens["shadow"]["tokens"]:
        lines.append(f"--{tok['name']}: {tok['value'][theme]};")
    return lines


def _type_lines(tokens: dict) -> list[str]:
    fams = tokens["type"]["families"]
    lines = [f"--font-{name}: {stack};" for name, stack in fams.items()]
    for group in tokens["type"]["groups"]:
        family = group["family"]
        for style in group["styles"]:
            name = style["name"]
            lines.append(
                f"--type-{name}: {style['fontWeight']} {style['fontSize']}/{style['lineHeight']} var(--font-{family});"
            )
            if style.get("letterSpacing"):
                lines.append(f"--type-{name}-tracking: {style['letterSpacing']};")
    return lines


def render(tokens: dict) -> str:
    shared: list[str] = []
    shared += _type_lines(tokens)
    for section in ("spacing", "radius", "layout"):
        shared += [f"--{tok['name']}: {tok['value']};" for tok in tokens[section]["tokens"]]
    shared += [f"--{name}: {value};" for name, value in MOTION.items()]

    aliases = [f"--{name}: {value};" for name, value in LEGACY_ALIASES.items()]
    light = _theme_lines(tokens, "light")
    dark = _theme_lines(tokens, "dark")

    parts = [
        "/* StonePi design tokens. GENERATED by packages/stonepi_brand/build_tokens.py from\n"
        "   tokens.json; do not edit by hand. Theme: data-theme=\"dark|light\" on <html>\n"
        "   (set by each app's theme boot); without it the system preference applies. */",
        _block(":root", shared),
        _block(":root", light),
        "@media (prefers-color-scheme: dark) {\n" + _block(':root:not([data-theme="light"])', dark, "  ") + "\n}",
        _block('[data-theme="light"]', light),
        _block('[data-theme="dark"]', dark),
        "/* Older names used by app stylesheets, mapped to roles. */",
        _block(":root", aliases),
    ]
    return "\n\n".join(parts) + "\n"


def main(argv: list[str]) -> int:
    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
    css = render(tokens)
    targets = [TARGET, *(t for t in EXTRA_TARGETS if t.parent.is_dir())]
    if "--check" in argv:
        stale = [t for t in targets if not t.exists() or t.read_text(encoding="utf-8") != css]
        for target in stale:
            print(f"{target} is stale; run build_tokens.py", file=sys.stderr)
        return 1 if stale else 0
    for target in targets:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(css, encoding="utf-8", newline="\n")
        print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
